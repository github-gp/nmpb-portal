// Helper: aggregate by city for map dots
export const getCityAggregates = (projects = PROJECTS) => {
  const map = {};
  projects.forEach(p => {
    const key = `${p.city}|${p.state}`;
    if (!map[key]) {
      map[key] = {
        city: p.city,
        state: p.state,
        lat: p.lat,
        lng: p.lng,
        count: 0,
        totalFund: 0,
      };
    }
    map[key].count += 1;
    map[key].totalFund += p.fund;
  });
  return Object.values(map);
};